/*
 * 04 · 打印 2 ~ n 之间的所有素数（从大到小）
 * ------------------------------------------------------------
 * 题目：输入一个上限 n，把 2 到 n 之间的素数全部打印出来，大的在前。
 * 输入：20       输出：19 17 13 11 7 5 3 2（每行一个）
 *
 * 思路：外层从 n 往下试到 2；内层判断 k 是不是素数，
 *      试除只试到 i * i <= k —— 因为如果 k 有因子，
 *      必有一个小于等于根号 k，试过头就是白费力气。
 *
 * 易错点：
 *   1. 内层的 isPrime 必须每轮重置成 1，否则一旦变成 0 就再也回不来。
 *   2. 内层一旦发现因子就 break，但 break 只跳出内层，外层照常继续。
 *   3. 条件写 i <= k / 2 也能对，但效率差一截；写 i < k 更差。
 */

#include <stdio.h>

int main(void)
{
    int n, k, i, isPrime;

    printf("请输入上界 n：\n");
    if (scanf("%d", &n) != 1) {
        printf("输入格式不对\n");
        return 1;
    }

    /* 从大到小枚举，天然满足"大的在前" */
    for (k = n; k >= 2; k--) {
        isPrime = 1;                    /* 每一轮都要重置 */

        /* 只试到根号 k：i * i <= k 避免引入 sqrt 和浮点误差 */
        for (i = 2; i * i <= k; i++) {
            if (k % i == 0) {
                isPrime = 0;            /* 找到因子，不是素数 */
                break;
            }
        }

        if (isPrime)
            printf("%d\n", k);
    }

    return 0;
}
