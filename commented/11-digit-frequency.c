/*
 * 11 · 统计 0~9 每个数字出现了几次
 * ------------------------------------------------------------
 * 题目：不断读入 0~9 的数字（输入 -1 结束），最后统计每个数字出现次数。
 * 输入：1 1 2 3 -1
 * 输出：0: 0  1: 2  2: 1  3: 1  4~9: 0
 *
 * 思路：这是"桶计数"最基础的形态 ——
 *      数字本身就是下标，count[x]++ 就完成了计数，不需要 10 个 if。
 *
 * 易错点：
 *   1. 数组必须初始化成 {0}，否则里面是随机值，加出来是垃圾数据。
 *   2. 一定要先判断范围再 count[x]++，否则输入 99 就越界写到数组外面了。
 *      这类越界在 C 里不会报错，但会悄悄改坏别的变量。
 *   3. 计数数组的长度就是"桶"的数量，下标 0~9 需要 10 个桶。
 */

#include <stdio.h>

int main(void)
{
    int count[10] = {0};      /* 10 个桶，全部清零 */
    int x, i;

    printf("请输入数字（0 ~ 9，输入 -1 结束）：\n");
    if (scanf("%d", &x) != 1)
        return 1;

    while (x != -1) {
        if (x >= 0 && x <= 9) /* 先挡掉越界值，再计数 */
            count[x]++;
        if (scanf("%d", &x) != 1)
            break;
    }

    for (i = 0; i < 10; i++)
        printf("%d: %d\n", i, count[i]);

    return 0;
}
