/*
 * 01 · 三个数从大到小排序
 * ------------------------------------------------------------
 * 题目：输入三个整数，按从大到小的顺序输出。
 * 输入：1 2 3     输出：从大到小：3 2 1
 *
 * 思路：不想用数组、也不想用排序算法，只靠三次"两两比较 + 交换"。
 *      先把 a 和 b 换好，再把 b 和 c 换好，此时 c 一定是最小的；
 *      但换完之后 a、b 的大小关系可能被破坏，所以要再比一次 a、b。
 *      这三步做完，a >= b >= c 一定成立。
 *
 * 易错点：
 *   1. 三次比较的顺序不能乱。写完第 2 步后必须补第 3 步。
 *   2. 交换要用临时变量 t，写成 a=b; b=a; 会把两个数变成一样。
 *   3. scanf 的返回值和参数个数比较，能挡住"用户输入了字母"的情况。
 */

#include <stdio.h>

int main(void)
{
    int a, b, c, t;          /* t 是交换用的临时变量 */

    printf("请输入三个整数（空格分隔）：\n");

    /* scanf 返回成功读入的项数；不等于 3 说明用户没按格式输入 */
    if (scanf("%d %d %d", &a, &b, &c) != 3) {
        printf("输入格式不对\n");
        return 1;
    }

    /* 第 1 步：让 a >= b */
    if (a < b) { t = a; a = b; b = t; }

    /* 第 2 步：让 b >= c，c 成为三者里最小的 */
    if (b < c) { t = b; b = c; c = t; }

    /* 第 3 步：上一步可能把 a 和 b 的顺序弄反了，再修一次 */
    if (a < b) { t = a; a = b; b = t; }

    printf("从大到小：%d %d %d\n", a, b, c);
    return 0;
}
