/*
 * 06 · 水仙花数 / 自幂数
 * ------------------------------------------------------------
 * 题目：输入位数 n，输出所有 n 位自幂数
 *      （每位数字的 n 次方之和等于它本身）。
 *      n = 3 时就是 153、370、371、407 这四个"水仙花数"。
 *
 * 思路：先算出 n 位数的起点 first = 10^(n-1)，然后在 [first, 10*first) 里逐个试。
 *      对每个数，拆出每一位，累加 d 的 n 次方，最后和原数比。
 *
 * 易错点：
 *   1. 次方不要用 pow：它是浮点函数，算 153 这种整数容易出现 152.99999。
 *      用一层 for 循环连乘更稳。
 *   2. 拆位时 t 会被除到 0，所以原数要另存一份。
 *   3. n 太大时循环量爆炸（7 位数要试 900 万个），所以这里限制到 7 位。
 */

#include <stdio.h>

int main(void)
{
    int n, i, j, digits, first = 1, t, d, sum, p;

    printf("请输入位数 n（3 就是水仙花数）：\n");
    if (scanf("%d", &n) != 1 || n < 1 || n > 7) {
        printf("位数取 1 ~ 7\n");
        return 1;
    }

    /* first = 10^(n-1)，比如 n=3 时 first=100 */
    for (i = 1; i < n; i++)
        first *= 10;

    for (i = first; i < first * 10; i++) {
        t = i;                 /* t 用来拆位，i 保留原值 */
        sum = 0;

        while (t > 0) {
            d = t % 10;        /* 取出最低位 */
            t /= 10;
            p = 1;
            for (j = 0; j < n; j++)
                p *= d;        /* 手算 d 的 n 次方，避免浮点误差 */
            sum += p;
        }

        if (sum == i)
            printf("%d\n", i);
    }

    return 0;
}
