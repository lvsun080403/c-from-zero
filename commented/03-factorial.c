/*
 * 03 · 求 n 的阶乘
 * ------------------------------------------------------------
 * 题目：输入 n，输出 n! = 1 × 2 × ... × n。
 * 输入：5        输出：5! = 120
 *
 * 思路：阶乘是"累乘"，所以初值必须给 1 而不是 0；
 *      循环变量从 1 走到 n，每轮把 i 乘进去。
 *
 * 易错点：
 *   1. fact 初值写成 0，无论怎么乘都是 0 —— 初学者最常见的一个 bug。
 *   2. int 只有 32 位，13! = 6227020800 已经装不下，会变成负数。
 *      所以这里直接挡掉 n > 12 的情况，而不是让程序"算出"一个错答案。
 *   3. for 循环体内只有一条语句时可以不写花括号，但建议写上，改起来不容易错。
 */

#include <stdio.h>

int main(void)
{
    int n, i;
    int fact = 1;            /* 累乘的初值必须是 1 */

    printf("请输入 n（0 ~ 12）：\n");
    if (scanf("%d", &n) != 1 || n < 0) {
        printf("请输入非负整数\n");
        return 1;
    }

    /* 12! = 479001600 还在 int 范围内，13! 就越界了 */
    if (n > 12) {
        printf("13! 已经超出 int 范围，这里只算到 12!\n");
        return 1;
    }

    for (i = 1; i <= n; i++)
        fact *= i;           /* 等价于 fact = fact * i */

    printf("%d! = %d\n", n, fact);
    return 0;
}
