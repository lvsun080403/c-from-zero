/*
 * 08 · 求 a + aa + aaa + ... 的和
 * ------------------------------------------------------------
 * 题目：输入数字 a 和项数 n，求 a + aa + aaa + ...（共 n 项）的值。
 * 输入：2 3      输出：246        （2 + 22 + 222 = 246）
 *
 * 思路：每一项都是上一项"左移一位再补上 a"，
 *      所以不用真的把 a 乘很多次，只要 t = t * 10 + a 一路递推即可，
 *      边递推边累加。
 *
 * 易错点：
 *   1. a 和 n 别写反。常见的输入是 "2 3"，代表 2、3 项。
 *   2. t 初值必须是 0，sum 也必须是 0。
 *   3. 原作业里还有一段把 sum 反复除 10 再累加的冗余循环，这里删掉了 ——
 *      它算出来的数没有实际含义，只会让结果看起来莫名其妙。
 */

#include <stdio.h>

int main(void)
{
    int a, n, i;
    int t = 0;               /* 当前这一项 */
    int sum = 0;             /* 累加结果 */

    printf("请输入 a 和 n（例如 2 3 表示 2 + 22 + 222）：\n");
    if (scanf("%d %d", &a, &n) != 2 || n < 1) {
        printf("输入格式不对\n");
        return 1;
    }

    for (i = 1; i <= n; i++) {
        t = t * 10 + a;      /* 2 -> 22 -> 222 ... 一位一位往上长 */
        sum += t;
    }

    printf("%d\n", sum);
    return 0;
}
