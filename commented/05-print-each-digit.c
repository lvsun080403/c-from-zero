/*
 * 05 · 从高位到低位逐位输出一个整数
 * ------------------------------------------------------------
 * 题目：输入一个整数，把它的每一位从左到右打印出来，用空格隔开。
 * 输入：12345    输出：1 2 3 4 5
 *
 * 思路：取低位很容易（%10），取高位才难。
 *      所以先算出一个"掩码" mask —— 和这个数位数一样长的 10 的幂，
 *      比如 12345 的 mask 是 10000。
 *      之后每轮：a / mask 得到最高位，a %= mask 把它去掉，mask /= 10 右移一位。
 *
 * 易错点：
 *   1. mask 要从 1 开始乘到"位数 - 1"次，写成 a / 10 才刚好。
 *   2. 每轮结束前 a 必须 %= mask，不能忘。
 *   3. 空格的输出位置：最后一位后面不要再补空格。
 */

#include <stdio.h>

int main(void)
{
    int a, mask = 1, t;

    printf("请输入一个正整数：\n");
    if (scanf("%d", &a) != 1 || a < 0) {
        printf("请输入非负整数\n");
        return 1;
    }

    /* 求掩码：12345 -> 10000 */
    for (t = a / 10; t > 0; t /= 10)
        mask *= 10;

    while (mask > 0) {
        printf("%d", a / mask);   /* 最高位 */
        a %= mask;                /* 去掉最高位 */
        mask /= 10;               /* 掩码右移一位 */
        if (mask >= 1)
            printf(" ");          /* 最后一位后面不打空格 */
    }
    printf("\n");

    return 0;
}
